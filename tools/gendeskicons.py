#!/usr/bin/env python3
"""Generate 1bpp DeskHop desk icons for the Prospector screen (src/desk_icons.c).

The desk strip draws DeskHop's monitors as plain LVGL boxes; these are the
three marks that go on top of them, at 12x12:

  U+E040  arrow       pointer is absolute -- drawn cut out of the lit monitor
  U+E041  crosshair   pointer is relative -- the same
  U+E042  padlock     switching is locked -- sits in the border gap

Drawn as ASCII art rather than from primitives: at 12 px every pixel is a
decision, and a grid you can read is easier to get right than geometry you
have to imagine rasterised.

Run:  python3 tools/gendeskicons.py
"""
import os

W = 12
H = 12

# Classic pointer, tail included. Offset three columns in so it sits centred on
# its own visual mass rather than on the box.
ARROW = """
...#........
...##.......
...###......
...####.....
...#####....
...######...
...#######..
...####.....
...##.##....
...#..##....
.......##...
.......##...
"""

# A ring with four ticks. Ticks are 2 px wide because the box is even-sized,
# so a 1 px tick could only ever be off-centre by half a pixel.
CROSSHAIR = """
.....##.....
.....##.....
...######...
..##....##..
..#......#..
###..##..###
###..##..###
..#......#..
..##....##..
...######...
.....##.....
.....##.....
"""

# Ten wide, not twelve: it sits in a 12 px border gap and must not touch the
# monitors either side of it.
PADLOCK = """
....####....
...##..##...
...#....#...
...#....#...
.##########.
.##########.
.####..####.
.####..####.
.##########.
.##########.
.##########.
............
"""


def parse(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == H, f"expected {H} rows, got {len(rows)}"
    for r in rows:
        assert len(r) == W, f"row {r!r} is {len(r)} wide, expected {W}"
    return [[1 if c == "#" else 0 for c in r] for r in rows]


glyphs = [("arrow", parse(ARROW)), ("crosshair", parse(CROSSHAIR)), ("padlock", parse(PADLOCK))]


def to_bytes(g):
    """Pack 1bpp rows continuously, with no per-row byte alignment -- LVGL's
    font format is one bit stream per glyph. See genperiphicons.py."""
    bits = []
    for row in g:
        bits.extend(row)
    out = []
    for i in range(0, len(bits), 8):
        byte = 0
        for b, v in enumerate(bits[i : i + 8]):
            if v:
                byte |= 1 << (7 - b)
        out.append(byte)
    return out


out = ["#include <lvgl.h>\n"]
out.append("""
/*
 * 1bpp DeskHop desk icons, generated by tools/gendeskicons.py.
 * DO NOT EDIT BY HAND -- re-run the generator:
 *
 *     python3 tools/gendeskicons.py
 *
 * It rewrites this file, including the running glyph_dsc indices.
 *
 *   U+E040 "\\xEE\\x81\\x80"  arrow      (absolute pointer)
 *   U+E041 "\\xEE\\x81\\x81"  crosshair  (relative pointer)
 *   U+E042 "\\xEE\\x81\\x82"  padlock    (switching locked)
 */""")

out.append("static const uint8_t desk_icons_bitmap[] = {")
idx = 0
for name, g in glyphs:
    bs = to_bytes(g)
    out.append(f"    /* {name}  {W}x{H}  index {idx} */")
    for i in range(0, len(bs), 8):
        out.append("    " + " ".join(f"0x{v:02X}," for v in bs[i : i + 8]))
    idx += len(bs)
out.append("};\n")

out.append('/* glyph 0 is the "not found" sentinel required by LVGL */')
out.append("static const lv_font_fmt_txt_glyph_dsc_t desk_icons_glyph_dsc[] = {")
out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
idx = 0
for name, g in glyphs:
    out.append(
        f"    {{.bitmap_index = {idx}, .adv_w = {W * 16}, "
        f".box_w = {W}, .box_h = {H}, .ofs_x = 0, .ofs_y = 0}},"
    )
    idx += len(to_bytes(g))
out.append("};\n")

out.append("/* FORMAT0_TINY: contiguous range, glyph_id = glyph_id_start + (cp - range_start) */")
out.append(
    """static const lv_font_fmt_txt_cmap_t desk_icons_cmaps[] = {
    {
        .range_start       = 0xE040,
        .range_length      = %d,
        .glyph_id_start    = 1,
        .unicode_list      = NULL,
        .glyph_id_ofs_list = NULL,
        .list_length       = 0,
        .type              = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY,
    },
};
"""
    % len(glyphs)
)

out.append(
    """static const lv_font_fmt_txt_dsc_t desk_icons_dsc = {
    .glyph_bitmap  = desk_icons_bitmap,
    .glyph_dsc     = desk_icons_glyph_dsc,
    .cmaps         = desk_icons_cmaps,
    .kern_dsc      = NULL,
    .kern_scale    = 0,
    .cmap_num      = 1,
    .bpp           = 1,
    .kern_classes  = 0,
    .bitmap_format = 0,
};

const lv_font_t desk_icons = {
    .get_glyph_dsc       = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap    = lv_font_get_bitmap_fmt_txt,
    .line_height         = %d,
    .base_line           = 0,
    .subpx               = LV_FONT_SUBPX_NONE,
    .underline_position  = -1,
    .underline_thickness = 1,
    .dsc                 = &desk_icons_dsc,
    .fallback            = NULL,
};"""
    % H
)

dest = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "desk_icons.c"
)
with open(dest, "w") as fh:
    fh.write("\n".join(out) + "\n")
print(f"wrote {dest}")
