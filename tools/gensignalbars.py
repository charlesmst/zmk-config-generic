#!/usr/bin/env python3
"""Generate 1bpp antenna signal bars for the Prospector screen (src/signal_bars.c).

dongle_icons.c already carries bars, but at 8x10 -- sized for a 128x64 OLED.
On the Prospector's 1.69" panel that is a speck, and a drop from four bars to
two is easy to miss entirely. These are 32x26: same idiom, legible across a
desk.

Six glyphs. U+E020..U+E024 are 0 to 4 bars lit; U+E025 is all four, meant to be
drawn underneath in a dim colour so the unlit remainder still reads as "bars
that could be filled" -- the way iOS shows cellular strength -- rather than
emptiness.

Run:  python3 tools/gensignalbars.py
"""
import os

W = 32
H = 26

# Four bars, 4 wide with a 3 px gutter: 4*4 + 3*3 = 25, centred in 32.
# Slimmer than the first cut -- at 6 px they read as blocks rather than as a
# signal meter.
BAR_W = 4
GAP = 3
X0 = 3

# Rising heights. Shortest still has real presence; tallest leaves a pixel at
# the top so the glyph is not flush against the line box.
HEIGHTS = [9, 14, 20, 25]


def blank():
    return [[0] * W for _ in range(H)]


def bar(g, index, lit=True):
    """Draw one bar, bottom-aligned, with its top corners clipped."""
    if not lit:
        return
    x0 = X0 + index * (BAR_W + GAP)
    x1 = x0 + BAR_W - 1
    top = H - HEIGHTS[index]
    for y in range(top, H):
        for x in range(x0, x1 + 1):
            # Clip the two top corners. A 1 px nick is all it takes to read as
            # rounded at this size, and it matches the soft caps on the arc.
            if y == top and (x == x0 or x == x1):
                continue
            g[y][x] = 1


def bars(count):
    g = blank()
    for i in range(4):
        bar(g, i, lit=i < count)
    return g


def to_bytes(g):
    """Pack 1bpp rows continuously, with no per-row byte alignment.

    This is what LVGL's font format expects: each glyph is a single bit stream
    of box_w * box_h pixels, padded only at the very end to a byte boundary.
    Padding every *row* instead works by accident whenever the width is a
    multiple of 8 and shears the glyph into diagonal stripes when it is not --
    which is exactly what a 34 px icon rendered as.
    """
    w = len(g[0])
    bits = []
    for row in g:
        bits.extend(row[:w])
    out = []
    for i in range(0, len(bits), 8):
        byte = 0
        for b, v in enumerate(bits[i : i + 8]):
            if v:
                byte |= 1 << (7 - b)
        out.append(byte)
    return out


glyphs = [(f"bars{n}", bars(n)) for n in range(5)] + [("bars_track", bars(4))]

for name, g in glyphs:
    print(f"--- {name} {W}x{H} ---")
    for row in g:
        print("".join("#" if c else "." for c in row))
    print()

out = ["#include <lvgl.h>\n"]
out.append("""
/*
 * 1bpp antenna signal bars, generated by tools/gensignalbars.py.
 * DO NOT EDIT BY HAND -- re-run the generator:
 *
 *     python3 tools/gensignalbars.py
 *
 * It rewrites this file, including the running glyph_dsc indices.
 *
 * dongle_icons.c has bars too, but at 8x10 for a 128x64 OLED. These are 32x26
 * for the Prospector's 1.69" panel, where the small ones were unreadable.
 *
 *   U+E020 "\\xEE\\x80\\xA0"  0 bars
 *   U+E021 "\\xEE\\x80\\xA1"  1 bar
 *   U+E022 "\\xEE\\x80\\xA2"  2 bars
 *   U+E023 "\\xEE\\x80\\xA3"  3 bars
 *   U+E024 "\\xEE\\x80\\xA4"  4 bars
 *   U+E025 "\\xEE\\x80\\xA5"  all four, for the dim track drawn underneath
 */""")

out.append("static const uint8_t signal_bars_bitmap[] = {")
idx = 0
for name, g in glyphs:
    bs = to_bytes(g)
    out.append(f"    /* {name}  {W}x{H}  index {idx} */")
    for i in range(0, len(bs), 8):
        out.append("    " + " ".join(f"0x{v:02X}," for v in bs[i : i + 8]))
    idx += len(bs)
out.append("};\n")

out.append('/* glyph 0 is the "not found" sentinel required by LVGL */')
out.append("static const lv_font_fmt_txt_glyph_dsc_t signal_bars_glyph_dsc[] = {")
out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
idx = 0
for name, g in glyphs:
    out.append(
        f"    {{.bitmap_index = {idx}, .adv_w = {W * 16}, "
        f".box_w = {W}, .box_h = {H}, .ofs_x = 0, .ofs_y = 0}},"
    )
    idx += len(to_bytes(g))
out.append("};\n")

out.append("/* FORMAT0_TINY: contiguous range, glyph_id = glyph_id_start + (cp - range_start) */")
out.append(
    """static const lv_font_fmt_txt_cmap_t signal_bars_cmaps[] = {
    {
        .range_start       = 0xE020,
        .range_length      = %d,
        .glyph_id_start    = 1,
        .unicode_list      = NULL,
        .glyph_id_ofs_list = NULL,
        .list_length       = 0,
        .type              = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY,
    },
};
"""
    % len(glyphs)
)

out.append(
    """static const lv_font_fmt_txt_dsc_t signal_bars_dsc = {
    .glyph_bitmap  = signal_bars_bitmap,
    .glyph_dsc     = signal_bars_glyph_dsc,
    .cmaps         = signal_bars_cmaps,
    .kern_dsc      = NULL,
    .kern_scale    = 0,
    .cmap_num      = 1,
    .bpp           = 1,
    .kern_classes  = 0,
    .bitmap_format = 0,
};

const lv_font_t signal_bars = {
    .get_glyph_dsc       = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap    = lv_font_get_bitmap_fmt_txt,
    .line_height         = %d,
    .base_line           = 0,
    .subpx               = LV_FONT_SUBPX_NONE,
    .underline_position  = -1,
    .underline_thickness = 1,
    .dsc                 = &signal_bars_dsc,
    .fallback            = NULL,
};"""
    % H
)

dest = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "signal_bars.c"
)
with open(dest, "w") as fh:
    fh.write("\n".join(out) + "\n")
print(f"wrote {dest}")
